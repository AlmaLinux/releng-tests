"""A NEVRA must name exactly one artifact, everywhere it appears.

``name-epoch:version-release.arch`` is RPM's identity. Two files that
share a NEVRA but differ in bytes are, as far as every tool in the
stack is concerned, the same package — ``dnf`` will happily install
whichever copy a given mirror or pipeline stage hands it, and no
upgrade path will ever reconcile them. The only correct number of such
pairs in a release is zero.

The existing parity tests check this *within* one release:
``test_noarch_parity`` invariant (A) asserts same-NEVRA-same-sha256
across arches and repos — but only for ``noarch`` packages, and only
for the one source under test. Nothing compared a release against the
other places its own packages live. This module does, and it covers
every arch, not just ``noarch``.

What it catches, concretely: a package rebuilt or re-signed without a
release bump between two stages of the pipeline (compose → internal
beta → published beta → GA), and a stale artifact left behind on a
mirror when a same-NEVRA replacement was published elsewhere. Both
look like nothing at all in a per-release check, because inside either
release the file is perfectly self-consistent.

Reference selection
-------------------
The invariant is unconditional — a NEVRA shared by *any* two
repositories must carry the same bytes, whatever releases they belong
to — so the reference does not have to be "the matching release". It
only has to be somewhere the same NEVRAs actually turn up, otherwise
the test is a no-op that reports green.

Shared-NEVRA counts measured on ``x86_64`` when this module was
written, for each candidate reference:

==================  ==================  =================
source under test   candidate           shared NEVRAs
==================  ==================  =================
``beta`` 10.3       ``pungi`` 10.3      4354
``beta`` 10.3       ``stable`` 10.2     3971
``pungi`` 10.3      ``stable`` 10.2     3956
``pulp`` 10.3       ``pungi`` 10.3      1744
``pulp`` 10.3       ``stable`` 10.2     **0**
``stable`` 10.2     ``beta`` 10.2       619 (BaseOS only)
``stable`` 10.2     ``stable`` 10.1     **0** — 404
==================  ==================  =================

Two of those zeroes drive the mapping in :data:`_REFERENCES`, and
neither is obvious from the outside:

* ``pulp``'s layered internal-beta carries only freshly built
  packages, so it shares no NEVRA at all with the previous GA.
  Comparing the two would assert nothing. Its packages do reach the
  compose, so that is what it is checked against.
* a **superseded minor is pruned from the public mirror** — once
  10.2 shipped, ``repo.almalinux.org/almalinux/10.1`` began answering
  404 (the same pruning that makes ``test_iso_presence`` fail on an
  old minor). So "previous minor" is a dead reference for a
  ``stable`` run, which is instead compared against the **beta of its
  own version**: vault keeps every past beta, and "the GA ships what
  the beta shipped" is the invariant worth asserting there anyway.
  ``pungi`` keeps the previous minor because for a compose that minor
  is the *current* GA, not a superseded one, and is still served.

The per-arch counts of actually-compared NEVRAs go into the report via
``report_detail``, so a green row can be told apart from a row that
had nothing to compare.
"""

from __future__ import annotations

from collections.abc import Iterable

import pytest

from post_check.config import (
    arch_supports_major,
    load_architectures,
    load_sources,
    compute_prev_version,
)
from post_check.helpers import http, repodata
from post_check.helpers.repo_scan import collect_packages_by_arch

pytestmark = [pytest.mark.online, pytest.mark.release]


# source-under-test -> (reference source, how to derive its version).
#
# "previous_minor" derives X.(Y-1); "same" reuses the version string
# this run was given. The chain mirrors the pipeline — stable is
# checked against its own beta, beta against the compose, pulp against
# the compose — with pungi reaching back to the current GA since
# nothing earlier in the pipeline outlives a compose. See the module
# docstring for the measured overlap behind each choice.
_REFERENCES: dict[str, tuple[str, str]] = {
    "stable": ("beta", "same"),
    "beta": ("pungi", "same"),
    "pungi": ("stable", "previous_minor"),
    "pulp": ("pungi", "same"),
}


def _nevra(pkg: repodata.Package) -> str:
    """RPM identity as a flat string. Epoch is deliberately excluded.

    ``primary.xml`` reports an epoch of ``0`` for packages whose RPM
    header has none at all, and the two are not distinguishable here.
    Including it would therefore create spurious mismatches between
    repositories whose metadata was generated by different createrepo
    versions, which is a metadata-quality question rather than the
    byte-identity one this module asks.
    """
    return f"{pkg.name}-{pkg.version}-{pkg.release}.{pkg.arch}"


def compute_nevra_checksum_conflicts(
    target: dict[str, dict[str, str]],
    reference: dict[str, dict[str, str]],
    *,
    target_label: str = "target",
    reference_label: str = "reference",
) -> list[str]:
    """Pure check: NEVRAs present in both sides with differing checksums.

    Input shape for both sides::

        {arch: {nevra: checksum}}

    Output: human-readable lines, empty when the two agree on every
    NEVRA they share.

    Split out from the test body so the meta-tests in
    ``tests/internal/test_assertions_actually_fire.py`` can prove both
    the detection and the rendering fire on synthetic input, with no
    HTTP involved.
    """
    failures: list[str] = []
    for arch in sorted(target):
        ref = reference.get(arch)
        if not ref:
            continue
        tgt = target[arch]
        conflicts = sorted(
            n for n in tgt.keys() & ref.keys() if tgt[n] != ref[n]
        )
        if not conflicts:
            continue
        failures.append(
            f"[{arch}] {len(conflicts)} NEVRA(s) with differing content "
            f"between {target_label} and {reference_label}:"
        )
        for n in conflicts:
            failures.append(f"  {n}")
            failures.append(f"    {target_label:<24} sha256={tgt[n]}")
            failures.append(f"    {reference_label:<24} sha256={ref[n]}")
    return failures


def _all_arches(major: str | None = None) -> tuple[str, ...]:
    """Every architecture published for AlmaLinux ``major``.

    Same rationale as the other parity modules: byte-identity is a
    property of the release, not of the operator's ``ALMA_ARCHES``
    subset, so narrowing the matrix must not narrow the invariant.
    """
    arches = sorted(load_architectures().keys())
    if major is not None:
        arches = [a for a in arches if arch_supports_major(a, major)]
    return tuple(arches)


def _checksums_by_arch(
    session,
    *,
    source: str,
    version: str,
    arches: Iterable[str],
    repos: Iterable[str],
) -> dict[str, dict[str, str]]:
    """``{arch: {nevra: checksum}}`` for one source.

    A NEVRA seen more than once inside the *same* source keeps the
    first checksum encountered. That intra-source case is already
    owned by ``test_noarch_parity`` invariant (A); re-reporting it here
    would duplicate findings across two tests in the same report.
    """
    collected = collect_packages_by_arch(
        session, source=source, version=version, arches=arches, repos=repos
    )
    return {
        arch: {_nevra(p): p.checksum for p in reversed(pkgs)}
        for arch, pkgs in collected.items()
    }


def test_nevra_content_matches_reference_source(runtime_config, report_detail):
    """No NEVRA may carry different bytes in two places at once.

    Collects every binary RPM of the release under test and of a
    reference source that is known to share NEVRAs with it, then
    asserts that every NEVRA they have in common resolves to the same
    sha256. A mismatch means two distinct files are circulating under
    one package identity.
    """
    source = runtime_config.source
    version = runtime_config.version

    ref_source, ref_rule = _REFERENCES[source]
    if ref_rule == "previous_minor":
        ref_version = compute_prev_version(version)
        if ref_version is None:
            pytest.skip(
                f"{source} {version}: no in-major predecessor to compare "
                f"against (x.0 is the first minor of its major, and "
                f"major-only versions carry no previous minor)"
            )
    else:
        ref_version = version

    major = version.split(".")[0]
    arches = _all_arches(major=major)
    repos = list(load_sources()[source]["repos"])
    ref_repos = list(load_sources()[ref_source]["repos"])

    s = http.session()
    target = _checksums_by_arch(
        s, source=source, version=version, arches=arches, repos=repos
    )
    reference = _checksums_by_arch(
        s, source=ref_source, version=ref_version, arches=arches, repos=ref_repos
    )

    target_label = f"{source} {version}"
    reference_label = f"{ref_source} {ref_version}"

    # A run that compared nothing is indistinguishable from a clean one
    # in the report unless the counts are spelled out. Zero shared
    # NEVRAs on every arch means the reference went stale (a compose
    # rolled over, a mirror was pruned) and the check silently stopped
    # testing anything.
    total_shared = 0
    for arch in arches:
        shared = len(target[arch].keys() & reference.get(arch, {}).keys())
        total_shared += shared
        report_detail(
            f"`{arch}`: {len(target[arch])} pkg(s) vs "
            f"{len(reference.get(arch, {}))} in {reference_label} — "
            f"{shared} shared NEVRA(s) compared"
        )
    assert total_shared, (
        f"{target_label} and {reference_label} share no NEVRA on any arch — "
        f"the reference is not comparable any more, so this check verified "
        f"nothing. Pick a different reference in _REFERENCES."
    )

    failures = compute_nevra_checksum_conflicts(
        target,
        reference,
        target_label=target_label,
        reference_label=reference_label,
    )
    assert not failures, "\n".join(failures)
